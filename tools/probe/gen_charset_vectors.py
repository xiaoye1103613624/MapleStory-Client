#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
T11 · 生成封包字符集对拍向量（Net/PacketCharset.cpp 的期望值）

oracle = Python 的 cp936/gbk codec（Python 的 gbk 即以微软 CP936 为蓝本）。
只收录 gbk 与 cp936 **编码结果一致**的串；不一致的条数单独报出来，
用来量化 notes/charset.md §5 里"Java GBK 与 CP936 扩展码位有差异"这条风险的实度量级。
期望值一律由 codec 算出，不手抄。

用法：
    python tools/probe/gen_charset_vectors.py            # 写 tools/probe/charset_vectors.h
    python tools/probe/gen_charset_vectors.py --report   # 只打印统计（stdout 全 ASCII）
"""

import argparse
import platform
import sys

OUT = "tools/probe/charset_vectors.h"

SAMPLES = [
    # --- 纯 ASCII：175 个既有调用点的绝大多数，必须字节级不变 ---
    "Admin",
    "Hello World",
    "xiao_ye",
    "Maple Story 83",
    # --- 常用汉字：真机已观测到的服务端文案 ---
    "已被监控",          # 档 F 的 AdminMonitor 文案（log-pairing.md §9.5）
    "已被监听",
    "对所有人",
    "新手冒险岛",
    "萧曳",
    "公会名称",
    "联盟公告",
    # --- 中英混排：聊天/公告的真实形态 ---
    "1 已被监控",
    "等级 100 已达成",
    "abc测试def",
    "[Notice] 你好，世界",
    # --- 全角标点与符号：v83 文案里高频 ---
    "【破功值：】",
    "（当前时间：）",
    "，。；！？：、",
    "①②③",
    "℃°±×÷",
    "→←↑↓",
    # --- GBK 尾字节落在 0x5C('\\') / 0x80 附近的历史坑位 ---
    "甓瓛",
    "纻",
]


def enc(text, codec):
    try:
        return text.encode(codec)
    except (UnicodeEncodeError, UnicodeDecodeError):
        return None


def hx(b):
    return "".join("\\x%02x" % c for c in b)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()

    vectors = []      # (utf8_hex, gbk_hex)
    disagree = []
    unencodable = []

    for t in SAMPLES:
        u = t.encode("utf-8")
        g1 = enc(t, "gbk")
        g2 = enc(t, "cp936")
        if g1 is None or g2 is None:
            unencodable.append(t)
            continue
        if g1 != g2:
            disagree.append((t, g1, g2))
            continue
        vectors.append((t, u, g1))

    # stdout 只打 ASCII（本机 shell 按 cp936 解 UTF-8，中文会花）
    print("python      : %s" % platform.python_version())
    print("samples     : %d" % len(SAMPLES))
    print("vectors     : %d" % len(vectors))
    print("gbk!=cp936  : %d" % len(disagree))
    print("unencodable : %d" % len(unencodable))
    for t, g1, g2 in disagree:
        print("  DISAGREE %s gbk=%s cp936=%s" % (t.encode("unicode_escape").decode(), hx(g1), hx(g2)))
    for t in unencodable:
        print("  SKIP     %s" % t.encode("unicode_escape").decode())

    if args.report:
        return 0

    lines = [
        "// Generated by tools/probe/gen_charset_vectors.py -- DO NOT EDIT.",
        "// oracle: Python %s codecs 'utf-8' + 'cp936'/'gbk' (values computed, not hand-copied)." % platform.python_version(),
        "// Only samples whose gbk and cp936 encodings are identical are listed.",
        "// Each entry: { utf8_hex, gbk_hex }. See tools/probe/charset_check.cpp.",
        "#pragma once",
        "",
        "static const struct CharsetVector",
        "{",
        "    const char* utf8;",
        "    const char* gbk;",
        "} CHARSET_VECTORS[] =",
        "{",
    ]
    for t, u, g in vectors:
        lines.append('    { "%s", "%s" },' % (hx(u), hx(g)))
    lines += [
        "};",
        "",
        "static const int CHARSET_VECTOR_COUNT = %d;" % len(vectors),
        "",
    ]

    with open(OUT, "wb") as f:
        f.write(("\n".join(lines)).encode("utf-8"))
    print("wrote       : %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
