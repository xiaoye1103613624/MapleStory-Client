$ErrorActionPreference = 'Stop'

$sqlPath = 'E:/project/BeiDou-Server_s9/gms-server/src/main/resources/db/migration/V1.0.53__maker_insert_data.sql'
$outPath = 'e:/project/MapleStory-Client/Data/MakerRecipes.h'

$sql = Get-Content -Raw $sqlPath

$start = $sql.IndexOf('INSERT IGNORE INTO `makercreatedata`')
if ($start -lt 0) { throw 'makercreatedata block not found' }
$rest = $sql.Substring($start)

$end = $rest.IndexOf('INSERT IGNORE INTO `makerrecipedata`')
if ($end -lt 0) {
    $end = $rest.IndexOf('INSERT IGNORE INTO `makerrewarddata`')
}
if ($end -lt 0) { $end = $rest.Length }
$block = $rest.Substring(0, $end)

# 每个元组: (id, itemid, req_level, req_maker_level, req_meso, req_item, req_equip, catalyst, quantity, tuc)
$tuples = [regex]::Matches($block, '\(([^)]*)\)')

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('#pragma once')
$out.Add('// Auto-generated by tools/gen_maker_recipes.ps1 from s9')
$out.Add('//   V1.0.53__maker_insert_data.sql (makercreatedata table).')
$out.Add('// Fallback recipe catalog for UIMaker when Maker.img (nlnx) is absent.')
$out.Add('// Mirrors s9 server recipe data so the Maker UI is usable without Maker.nx.')
$out.Add('// Fields order: itemId, meso, reqLevel, reqItem, reqEquip, catalyst, quantity')
$out.Add('#include <cstdint>')
$out.Add('')
$out.Add('struct MakerS9Recipe')
$out.Add('{')
$out.Add('    int32_t itemId;')
$out.Add('    int32_t meso;')
$out.Add('    int32_t reqLevel;')
$out.Add('    int32_t reqItem;')
$out.Add('    int32_t reqEquip;')
$out.Add('    int32_t catalyst;')
$out.Add('    int32_t quantity;')
$out.Add('};')
$out.Add('')
$out.Add('static const MakerS9Recipe g_maker_s9_recipes[] =')
$out.Add('{')

$count = 0
foreach ($m in $tuples) {
    $raw = $m.Groups[1].Value
    $fields = $raw.Split(',') | ForEach-Object { $_.Trim().Trim('`') }
    # 列名元组（含非数字）会被跳过
    if ($fields.Count -lt 10) { continue }
    try {
        $itemId   = [int]$fields[1]
        $reqLevel = [int]$fields[2]
        $meso     = [int]$fields[4]
        $reqItem  = [int]$fields[5]
        $reqEquip = [int]$fields[6]
        $catalyst = [int]$fields[7]
        $quantity = [int]$fields[8]
    } catch {
        continue
    }
    $out.Add("    {$itemId, $meso, $reqLevel, $reqItem, $reqEquip, $catalyst, $quantity},")
    $count++
}

$out.Add('};')
$out.Add("static const size_t g_maker_s9_recipes_n = sizeof(g_maker_s9_recipes) / sizeof(g_maker_s9_recipes[0]);")

Set-Content -Path $outPath -Value $out -Encoding utf8
Write-Host "Generated $count recipes -> $outPath"
