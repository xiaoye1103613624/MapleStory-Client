		// 手工表里的 lamp_id 是参考实现 kLamps 的下标；这里映射到 art 表。
		static const LampArt* art_for(int lamp_id)
		{
			switch (lamp_id)
			{
			case 0:  return &kLampArt[0];   // Lith Harbour
			case 6:  return &kLampArt[1];   // Henesys
			case 8:  return &kLampArt[2];   // Kerning City
			case 12: return &kLampArt[3];   // Perion (火盆)
			case 22: return &kLampArt[4];   // Ellinia (花灯)
			default: return nullptr;
			}
		}

		// 热点：本端 Map 合并根不含后加的 Obj img（真机三路探针实证：
		// A merged=type0 / B single=type5(bitmap) / C 合并根取不到）。
		// 因此所有灯 art 一律按文件独立加载：base()/Map/Obj/<bank>.img，
		// 与已成功的粒子 effect_img() 同为 nl::img_file::open_single。
		static nl::node obj_img(const char* bank)
		{
			static std::map<std::string, nl::node> cache;
			static std::map<std::string, std::unique_ptr<nl::img_file>> files;
			auto it = cache.find(bank);
			if (it != cache.end())
				return it->second;

			nl::node root;
#ifdef USE_NX
			const std::string& base = res::ResourceService::get().base();
			std::string path = base + "/Map/Obj/" + bank + ".img";
			std::ifstream in(path, std::ios::binary);
			if (in)
			{
				std::vector<char> buf((std::istreambuf_iterator<char>(in)),
					std::istreambuf_iterator<char>());
				try
				{
					auto f = std::make_unique<nl::img_file>();
					f->open_single(std::move(buf));
					root = f->root();
					files.emplace(bank, std::move(f));
				}
				catch (...)
				{
					root = nl::node();
				}
			}
#endif
			cache.emplace(bank, root);
			return root;
		}

		// 取 canvas：Obj art 的 bitmap 在 <dir>/<name>/<no>/0（实测 gaslamp/0/0=96x259）。
		// 若 <no> 本身已是 bitmap 则直接用（兼容其他结构）。
		static nl::node art_node(nl::node root, const char* dir, const char* name, const char* no)
		{
			if (!root)
				return nl::node();
			nl::node n = root[dir][name][no];
			if (!n)
				return nl::node();
			if (n.data_type() == nl::node::type::bitmap)
				return n;
			nl::node first = n["0"];
			return first.data_type() == nl::node::type::bitmap ? first : nl::node();
		}

		// 按 art 懒加载真实 sprite。
		static const Texture* lamp_texture(const LampArt& a)
		{
			static std::map<std::string, Texture> cache;
			std::string key = std::string(a.bank) + "/" + a.dir + "/" + a.name + "/" + a.no;
			auto it = cache.find(key);
			if (it != cache.end())
				return it->second.is_valid() ? &it->second : nullptr;

			Texture t;
#ifdef USE_NX
			// 首选参考表的 art；失败则兜底到本端确实存在的街灯（gaslamp 96x259）。
			nl::node n = art_node(obj_img(a.bank), a.dir, a.name, a.no);
			if (!n)
				n = art_node(obj_img("MapleMoonLamp2"), "street", "gaslamp", "0");
			if (n)
				t = Texture(n);
#endif
			auto res = cache.emplace(key, t);
			return res.first->second.is_valid() ? &res.first->second : nullptr;
		}

		void Lamps::update(float night_level, bool snap)
		{
			night_ = night_level;   // 光晕强度随夜色深入（淡→亮→暗）
			// 室内无路灯逻辑（对齐 bNight=bSky||underwater；无 tint 的图不点灯）。
			if (!State::get().allow_tint())
			{
				on_ = false;
				level_ = 0.0f;
				lit_since_ms_ = 0;
				return;
			}
			// 光敏迟滞（参考 lamps.cpp:415-450）：进入 0.35 开、回落到 0.28 才关。
			if (!on_ && night_level >= kOnLevel)
			{
				on_ = true;
				lit_since_ms_ = 0;   // 点亮时刻，之后按真实 TIMESTEP 累加
			}
			else if (on_ && night_level <= kOffLevel)
				on_ = false;
			if (on_)
				lit_since_ms_ += kTimestepMs;   // 原写死 16ms 实为 2 倍速（TIMESTEP=8ms）

			// 目标亮度：光敏全开=1；否则暮色段给一点弱光。
			float target = 0.0f;
			if (on_)
				target = 1.0f;
			else if (night_level > kDimFrom)
			{
				// 2026-11-22：bundle lamps.cpp:452-459 是 smoothstep(t)，分母用
				// ON-DIM_FROM。原线性 + 分母 (DIM_MAX-DIM_FROM) 是笔误曲线。
				float t = (night_level - kDimFrom) / (kOnLevel - kDimFrom);
				if (t < 0.0f) t = 0.0f; else if (t > 1.0f) t = 1.0f;
				target = t * t * (3.0f - 2.0f * t) * 0.35f;
			}

			// SNAP（进图 0x373D FLAG_SNAP）：bundle StepSwitch 直接赋值到位，
			// 不再"每次传送重新暖灯"——从根上消除切图后路灯几秒才亮。
			if (snap)
			{
				level_ = target;
				if (on_)
					lit_since_ms_ = kStaggerMs;   // 错峰已完成，全部灯立即常亮
				return;
			}

			// warmup 升 1200ms=150 帧、降 250ms=31 帧（TIMESTEP=8ms）；
			// 到位后恒定，无周期性呼吸（bundle lamps.cpp:212-224）。
			if (level_ < target)
			{
				const float step = 1.0f / kWarmupFrames;
				level_ = level_ + step < target ? level_ + step : target;
			}
			else if (level_ > target)
			{
				const float step = 1.0f / kCoolFrames;
				level_ = level_ - step > target ? level_ - step : target;
			}
		}

		void Lamps::draw(double viewx, double viewy, float alpha) const
		{
			const int map_id = Stage::get().get_mapid();
			const int16_t vw = Constants::Constants::get().get_viewwidth();
			const int16_t vh = Constants::Constants::get().get_viewheight();

			// 本地 lambda：画一盏灯（手工表或 GM 预览共用）。
			auto draw_one = [&](int x, int y, int lamp_id, float lit, float stagger)
			{
				const double sx = static_cast<double>(x) + viewx;
				// 2026-11-23：路灯整体上移，让光源贴近灯泡高度（原来偏低）。
				const double sy = static_cast<double>(y) + viewy + kLampLiftY;
				if (sx < -80 || sx > vw + 80 || sy < -80 || sy > vh + 80)
					return;
				const LampArt* art = art_for(lamp_id);
				const Texture* tex = art ? lamp_texture(*art) : nullptr;
				// 光晕强度随夜色深度从淡到亮再到暗（night_），叠加上错峰 stagger。
				const float ga = lit * stagger;
				const float glow_a = lit * stagger * night_; // 光晕专用：∝ 夜色深入
				if (tex == nullptr)
				{
					GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) - 3, static_cast<int16_t>(sy) - 84,
						6, 84, 0.16f, 0.14f, 0.12f, 0.95f * ga);
					GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) - 10, static_cast<int16_t>(sy) - 104,
						20, 22, 1.0f, 0.96f, 0.80f, 0.95f * ga);
					// 兜底灯（无 sprite）：径向柔光取代矩形光池，灯芯在灯柱顶端 sy-93。
					const int16_t fb_x = static_cast<int16_t>(sx);
					const int16_t fb_y = static_cast<int16_t>(sy) - 93;
					GraphicsGL::get().draw_glow(fb_x, fb_y, 150,
						1.0f, 0.88f, 0.60f, glow_a * 0.55f);
					GraphicsGL::get().draw_glow(fb_x, fb_y, 60,
						1.0f, 0.94f, 0.70f, glow_a * 0.45f);
					return;
				}
				// sprite 仍以 emitter0 为绘制锚点（保持既有对位，避免视觉回归）。
				const Emitter& e0 = art->emitters[0];
				tex->draw(DrawArgument(Point<int16_t>(
					static_cast<int16_t>(sx) + e0.dx,
					static_cast<int16_t>(sy) + e0.dy), ga));
				GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) + e0.dx - 6,
					static_cast<int16_t>(sy) + e0.dy - 8, 12, 12,
					1.0f, 0.90f, 0.71f, ga * 0.85f);
				// 2026-11-22：每个 emitter（灯泡）各有一处光源，逐字对齐 bundle
				// LAMPDEF.aEmitters + ApplyLamp 的 for-e 循环（lamps.cpp:942-955）。
				// 之前只画 emitter0 → 三灯泡灯（Henesys）只亮中间一个。
				// 光晕半径按 emitter 实测 radius 分级：小灯芯小光晕，外扩一层柔光。
				for (uint8_t e = 0; e < art->n_emitters && e < 4; e++)
				{
					const Emitter& em = art->emitters[e];
					const int16_t ex = static_cast<int16_t>(sx) + em.dx;
					const int16_t ey = static_cast<int16_t>(sy) + em.dy;
					const int16_t outer = static_cast<int16_t>(
						70 + em.radius * 6);               // 13px→148, 8px→118, 3px→88
					const int16_t inner = static_cast<int16_t>(em.radius * 3 + 10);
					GraphicsGL::get().draw_glow(ex, ey, outer,
						1.0f, 0.88f, 0.60f, glow_a * 0.55f);
					GraphicsGL::get().draw_glow(ex, ey, inner,
						1.0f, 0.94f, 0.76f, glow_a * 0.45f);
				}
			};

			// GM !lamp 预览：白天也常亮，方便量坐标（不依赖夜色门禁）。
			for (const auto& p : previews_)
			{
				if (p.map_id != map_id)
					continue;
				draw_one(p.x, p.y, p.lamp_id, 1.0f, 1.0f);
			}

			if (!State::get().allow_tint() || level_ <= 0.01f)
				return;

			int lamp_seq = 0;
			for (const auto& lamp : kManualLamps)
			{
				if (lamp.map_id != map_id)
					continue;
				// 2026-11-22：原 delay=seq*2600 线性递增，第12盏要等 31s。
				// bundle lamps.cpp:2008 是 (seq*977)%2600 循环相位——全部灯 2.6s 内点完。
				const uint32_t delay = (lamp_seq++ * kStaggerPhaseMs) % kStaggerMs;
				const int diff = static_cast<int>(lit_since_ms_) - static_cast<int>(delay);
				const float stagger = diff <= 0 ? 0.0f : (diff >= 1200 ? 1.0f : diff / 1200.0f);
				draw_one(lamp.x, lamp.y, lamp.lamp_id, level_, stagger);
			}
		}

		void Lamps::clear()
		{
			level_ = 0.0f;
			on_ = false;
			night_ = 0.0f;
			lit_since_ms_ = 0;
			previews_.clear();
		}

		void Lamps::apply_preview(uint8_t mode, uint8_t lamp_id, int32_t map_id, int32_t x, int32_t y)
		{
			// wire mode：0=place，1=clear 本图全部预览（LampPackets.java）。
			if (mode == 1)
			{
				previews_.erase(
					std::remove_if(previews_.begin(), previews_.end(),
						[map_id](const PreviewLamp& p) { return p.map_id == map_id; }),
					previews_.end());
				return;
			}
			PreviewLamp p;
			p.map_id = map_id;
			p.x = x;
			p.y = y;
			p.lamp_id = lamp_id;
			previews_.push_back(p);
		}
