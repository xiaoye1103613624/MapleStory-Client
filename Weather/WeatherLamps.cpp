		// 手工表里的 lamp_id 是参考实现 kLamps 的下标；这里映射到 art 表。
		static const LampArt* art_for(int lamp_id)
		{
			switch (lamp_id)
			{
			case 0:  return &kLampArt[0];   // Lith Harbour
			case 6:  return &kLampArt[1];   // Henesys
			case 8:  return &kLampArt[2];   // Kerning City
			case 12: return &kLampArt[3];   // Perion (火盆)
			case 22: return &kLampArt[4];   // Ellinia (花灯)
			default: return nullptr;
			}
		}

		// 热点：本端 Map 合并根不含后加的 Obj img（真机三路探针实证：
		// A merged=type0 / B single=type5(bitmap) / C 合并根取不到）。
		// 因此所有灯 art 一律按文件独立加载：base()/Map/Obj/<bank>.img，
		// 与已成功的粒子 effect_img() 同为 nl::img_file::open_single。
		static nl::node obj_img(const char* bank)
		{
			static std::map<std::string, nl::node> cache;
			static std::map<std::string, std::unique_ptr<nl::img_file>> files;
			auto it = cache.find(bank);
			if (it != cache.end())
				return it->second;

			nl::node root;
#ifdef USE_NX
			const std::string& base = res::ResourceService::get().base();
			std::string path = base + "/Map/Obj/" + bank + ".img";
			std::ifstream in(path, std::ios::binary);
			if (in)
			{
				std::vector<char> buf((std::istreambuf_iterator<char>(in)),
					std::istreambuf_iterator<char>());
				try
				{
					auto f = std::make_unique<nl::img_file>();
					f->open_single(std::move(buf));
					root = f->root();
					files.emplace(bank, std::move(f));
				}
				catch (...)
				{
					root = nl::node();
				}
			}
#endif
			cache.emplace(bank, root);
			return root;
		}

		// 取 canvas：Obj art 的 bitmap 在 <dir>/<name>/<no>/0（实测 gaslamp/0/0=96x259）。
		// 若 <no> 本身已是 bitmap 则直接用（兼容其他结构）。
		static nl::node art_node(nl::node root, const char* dir, const char* name, const char* no)
		{
			if (!root)
				return nl::node();
			nl::node n = root[dir][name][no];
			if (!n)
				return nl::node();
			if (n.data_type() == nl::node::type::bitmap)
				return n;
			nl::node first = n["0"];
			return first.data_type() == nl::node::type::bitmap ? first : nl::node();
		}

		// 按 art 懒加载真实 sprite。
		static const Texture* lamp_texture(const LampArt& a)
		{
			static std::map<std::string, Texture> cache;
			std::string key = std::string(a.bank) + "/" + a.dir + "/" + a.name + "/" + a.no;
			auto it = cache.find(key);
			if (it != cache.end())
				return it->second.is_valid() ? &it->second : nullptr;

			Texture t;
#ifdef USE_NX
			// 首选参考表的 art；失败则兜底到本端确实存在的街灯（gaslamp 96x259）。
			nl::node n = art_node(obj_img(a.bank), a.dir, a.name, a.no);
			if (!n)
				n = art_node(obj_img("MapleMoonLamp2"), "street", "gaslamp", "0");
			if (n)
				t = Texture(n);
#endif
			auto res = cache.emplace(key, t);
			return res.first->second.is_valid() ? &res.first->second : nullptr;
		}

		void Lamps::update(float night_level)
		{
			tick_ms_ += 16;

			// 光敏迟滞（参考 lamps.cpp:415-450）：进入 0.35 开、回落到 0.28 才关。
			// OFF 必须 >0——夜色归零后调用方停止推进，OFF=0 会让灯在白天常亮。
			if (!on_ && night_level >= kOnLevel)
				on_ = true;
			else if (on_ && night_level <= kOffLevel)
				on_ = false;

			// 目标亮度：光敏全开=1；否则暮色段给一点弱光（下限 0.14 以下没有）。
			float target = 0.0f;
			if (on_)
				target = 1.0f;
			else if (night_level > kDimFrom)
				target = (night_level - kDimFrom) / (kDimMax - kDimFrom) * 0.35f;

			// warmup 1200ms（参考 LAMP_WARMUP_MS）：约 75 帧线性升到目标。
			const float step = 1.0f / 75.0f;
			if (level_ < target) level_ = level_ + step < target ? level_ + step : target;
			else if (level_ > target) level_ = level_ - step > target ? level_ - step : target;

			// 灯芯呼吸（5 秒三角波 0.85..1.0，只调亮度不改开关）。
			breathe_ms_ += 16;
			if (breathe_ms_ >= kBreathePeriodMs)
				breathe_ms_ -= kBreathePeriodMs;
			const float phase = static_cast<float>(breathe_ms_) / static_cast<float>(kBreathePeriodMs);
			const float tri = phase < 0.5f ? phase * 2.0f : (1.0f - phase) * 2.0f;
			breathe_ = 0.85f + 0.15f * tri;
		}

		void Lamps::draw(double viewx, double viewy, float alpha) const
		{
			if (level_ <= 0.01f)
				return;
			const int map_id = Stage::get().get_mapid();
			const int16_t vw = Constants::Constants::get().get_viewwidth();
			const int16_t vh = Constants::Constants::get().get_viewheight();

			int lamp_seq = 0;
			for (const auto& lamp : kManualLamps)
			{
				if (lamp.map_id != map_id)
					continue;
				// 逐灯错峰（参考 LAMP_STAGGER_MS=2600ms/灯）：按灯序取相位，
				// 让同一 town 的灯在 ~1 秒内先后亮起，而不是齐刷刷。
				const uint32_t stagger_phase = (lamp_seq++ * 2600u) % 13000u;
				const float stagger = 0.55f + 0.45f * (
					static_cast<float>((tick_ms_ + stagger_phase) % 1300u) / 1300.0f);
				// 世界→屏幕照 Char.cpp:44（viewx 是相机偏移量 = vw/2 - 玩家世界x）：
				// screen = world + viewx。此前"- viewx + vw/2"符号反了导致灯画到屏外。
				const double sx = static_cast<double>(lamp.x) + viewx;
				const double sy = static_cast<double>(lamp.y) + viewy;
				if (sx < -80 || sx > vw + 80 || sy < -80 || sy > vh + 80)
					continue;
				const LampArt* art = art_for(lamp.lamp_id);
				const Texture* tex = art ? lamp_texture(*art) : nullptr;
				if (tex == nullptr)
				{
					// 真素材按文件独立加载失败时的最后兜底（正常不会走到）：
					// 自绘完整灯具 —— 灯柱 + 灯球 + 加色光晕 + 地面光池，绝不静默跳过。
					const float ga = level_ * stagger * breathe_ * alpha;
					// 灯柱（深色铸铁杆）
					GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) - 3, static_cast<int16_t>(sy) - 84,
						6, 84, 0.16f, 0.14f, 0.12f, 0.95f * ga);
					// 灯球（暖白）
					GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) - 10, static_cast<int16_t>(sy) - 104,
						20, 22, 1.0f, 0.96f, 0.80f, 0.95f * ga);
					// 加色光晕（近处亮、远处散）
					GraphicsGL::get().drawrectangle_add(static_cast<int16_t>(sx) - 34, static_cast<int16_t>(sy) - 128,
						68, 68, 1.0f, 0.88f, 0.55f, 0.20f * ga);
					GraphicsGL::get().drawrectangle_add(static_cast<int16_t>(sx) - 16, static_cast<int16_t>(sy) - 110,
						32, 32, 1.0f, 0.94f, 0.70f, 0.42f * ga);
					// 地面光池（照亮区域）
					GraphicsGL::get().drawrectangle_add(static_cast<int16_t>(sx) - 92, static_cast<int16_t>(sy) - 34,
						184, 68, 1.0f, 0.88f, 0.62f, 0.10f * ga);
					continue;
				}

				// 真实 sprite：sprite 原点在 bitmap 内，DrawArgument 位置即灯座世界点 + emitter 偏移。
				tex->draw(DrawArgument(Point<int16_t>(
					static_cast<int16_t>(sx) + art->ox,
					static_cast<int16_t>(sy) + art->oy),
					level_ * stagger * alpha));

				// 暖色灯芯：必须 LB_NORMAL（参考 lamps.cpp:406-410 实测：
				// 加色在白玻璃上出不了暖色，三通道一起 clip 到白；普通混合替换玻璃色，
				// 0.85 落在 (255,229,180)）。画在光晕之前，光晕叠在它外面。
				GraphicsGL::get().drawrectangle(static_cast<int16_t>(sx) + art->ox - 6,
					static_cast<int16_t>(sy) + art->oy - 8, 12, 12,
					1.0f, 0.90f, 0.71f, level_ * stagger * 0.85f * alpha);

				// 光池（照亮区域）：参考 lamps.cpp:136-138 的 light POOL，半径实测。
				// 用加色批次画，叠在地面上把地"照亮"，不是盖一层灰。
				const float lit = level_ * stagger * breathe_ * alpha;
				GraphicsGL::get().drawrectangle_add(
					static_cast<int16_t>(sx) - 96, static_cast<int16_t>(sy) - 40, 192, 80,
					1.0f, 0.88f, 0.62f, lit * 0.10f);
				GraphicsGL::get().drawrectangle_add(
					static_cast<int16_t>(sx) - 60, static_cast<int16_t>(sy) - 24, 120, 48,
					1.0f, 0.90f, 0.66f, lit * 0.16f);

				// 光晕：MapleMoonLamp.img/glow 真实美术 + 加色混合（参考 lamps.cpp:19
				// "light is a separate additive sprite"）。普通 alpha 会成灰块。
				if (const Texture* glow = glow_texture())
				{
					glow->draw(DrawArgument(Point<int16_t>(
						static_cast<int16_t>(sx) + art->ox,
						static_cast<int16_t>(sy) + art->oy),
						level_ * breathe_ * 0.55f * alpha));
				}
			}
		}

