	void TooltipLattice::draw(Point<int16_t> topleft, int16_t width, int16_t height) const
	{
		ensure();
		GraphicsGL& gl = GraphicsGL::get();
		const int16_t nx = (width + TILE_W - 1) / TILE_W;
		const int16_t ny = (height + TILE_H - 1) / TILE_H;
		for (int16_t iy = 0; iy < ny; ++iy)
		{
			for (int16_t ix = 0; ix < nx; ++ix)
			{
				const int16_t px = topleft.x() + ix * TILE_W;
				const int16_t py = topleft.y() + iy * TILE_H;
				const int16_t remx = width - ix * TILE_W;
				const int16_t remy = height - iy * TILE_H;
				const int16_t pw = remx < TILE_W ? remx : TILE_W;
				const int16_t ph = remy < TILE_H ? remy : TILE_H;
				gl.draw_raw(ATLAS_ID, px, py, pw, ph, 1.0f);
			}
		}
	}
