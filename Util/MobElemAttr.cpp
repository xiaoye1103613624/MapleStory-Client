		static const int ELEM_ATTR_COUNT = sizeof(ELEM_ATTR_TABLE) / sizeof(ELEM_ATTR_TABLE[0]);

		const char* mob_elem_attr(int32_t mobid)
		{
			int lo = 0;
			int hi = ELEM_ATTR_COUNT - 1;
			while (lo <= hi)
			{
				int mid = (lo + hi) / 2;
				int32_t cur = ELEM_ATTR_TABLE[mid].mobid;
				if (cur == mobid)
					return ELEM_ATTR_TABLE[mid].code;
				if (cur < mobid)
					lo = mid + 1;
				else
					hi = mid - 1;
			}
			return nullptr;
		}

		std::string elem_attr_display(const std::string& code)
		{
			if (code.empty())
				return std::string();

			auto elem_name = [](char c) -> const char* {
				switch (c)
				{
				case 'I': return "冰";
				case 'L': return "雷";
				case 'F': return "火";
				case 'S': return "毒";
				case 'H': return "圣";
				case 'D': return "暗";
				case 'P': return "物";
				default:  return nullptr;
				}
			};
			auto resist_name = [](char d) -> const char* {
				switch (d)
				{
				case '0': return "普通";
				case '1': return "免疫";
				case '2': return "抵抗";
				case '3': return "弱";
				default:  return nullptr;
				}
			};

			std::string out;
			for (size_t i = 0; i + 1 < code.size(); i += 2)
			{
				const char* en = elem_name(code[i]);
				const char* rn = resist_name(code[i + 1]);
				if (!en || !rn)
					continue;
				// 免疫/抵抗/弱才有展示价值，普通(0)略过以免冗长。
				if (code[i + 1] == '0')
					continue;
				if (!out.empty())
					out += " ";
				out += en;
				out += ":";
				out += rn;
			}
			return out;
		}
